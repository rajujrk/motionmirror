"use client";

import type { ButtonHTMLAttributes, ReactNode } from "react";

type Variant = "primary" | "plain" | "quiet";

const VARIANTS: Record<Variant, string> = {
  primary: "bg-tape text-white hover:bg-tape-deep disabled:bg-rule disabled:text-ink-soft",
  plain: "bg-sheen text-ink border border-ink hover:bg-white disabled:border-rule disabled:text-ink-soft",
  quiet: "text-ink underline underline-offset-3 hover:text-tape-deep disabled:text-ink-soft",
};

export function Button({
  variant = "plain",
  className = "",
  ...props
}: ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant }) {
  const shape = variant === "quiet" ? "" : "rounded-sm px-4 py-2 font-semibold";
  return (
    <button type="button" className={`${shape} ${VARIANTS[variant]} disabled:cursor-not-allowed ${className}`} {...props} />
  );
}

/** A dancer's spike mark: two crossed strips of tape. */
export function TapeX({ color = "var(--color-tape)", size = 24, className }: { color?: string; size?: number; className?: string }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" className={className}>
      <polygon points="3.2,5.4 5.6,3.1 20.9,18.4 18.5,20.8" fill={color} />
      <polygon points="18.6,3.2 20.8,5.5 5.4,20.9 3.1,18.5" fill={color} opacity="0.86" />
    </svg>
  );
}

/** Shown wherever output didn't come from a model. The wording is fixed by the product brief. */
export function MockTape({ detail }: { detail?: string }) {
  return (
    <div role="status" className="hazard-tape px-3 py-2 text-center text-sm">
      <span>MOCK / NO AI REPLACEMENT</span>
      {detail ? <span className="ml-2 font-normal!">{detail}</span> : null}
    </div>
  );
}

export function RealBadge({ experimental = false }: { experimental?: boolean }) {
  return (
    <span className="rounded-sm border border-real px-2 py-0.5 text-sm font-semibold text-real">
      {experimental ? "Experimental model output" : "Generated by the AI model"}
    </span>
  );
}

export function ErrorNote({ children }: { children: ReactNode }) {
  return (
    <p role="alert" className="border-l-4 border-tape bg-sheen px-3 py-2 text-sm">
      {children}
    </p>
  );
}

export function Hint({ children }: { children: ReactNode }) {
  return <p className="max-w-[65ch] text-sm text-ink-soft">{children}</p>;
}

export function StepHeading({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <header className="mb-5">
      <h2 className="mark-heading text-4xl sm:text-5xl">{title}</h2>
      {children ? <div className="mt-2 max-w-[65ch] text-ink-soft">{children}</div> : null}
    </header>
  );
}

/** The dark floor that video sits on. */
export function Stage({ children, className = "" }: { children: ReactNode; className?: string }) {
  return <div className={`overflow-hidden rounded-sm bg-floor ${className}`}>{children}</div>;
}
